    /**
     * Asocia cada campo del formulario con el dato que valida, para poder
     * resaltarlo en rojo cuando el controlador informa un error.
     */
    private void registrarCamposValidables() {
        camposFormulario.put(Campo.NOMBRE, txtNombre);
        camposFormulario.put(Campo.NIVEL, spnNivel);
        camposFormulario.put(Campo.PUNTOS_VIDA, spnPuntosVida);
        camposFormulario.put(Campo.ATRIBUTO, txtAtributo);
        camposFormulario.values().forEach(c -> bordesOriginales.put(c, c.getBorder()));
    }

    private static void bloquearEntradaInvalida(JSpinner spinner) {
        JFormattedTextField campo = ((JSpinner.DefaultEditor) spinner.getEditor()).getTextField();
        if (campo.getFormatterFactory() instanceof DefaultFormatterFactory fabrica
                && fabrica.getDefaultFormatter() instanceof DefaultFormatter formato) {
            formato.setAllowsInvalid(false);
            formato.setCommitsOnValidEdit(true);
        }
    }

