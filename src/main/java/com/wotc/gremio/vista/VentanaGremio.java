    private static String estadistica(String valor, String etiqueta) {
        return "<html><center><font size='5' color='#E3B341'><b>" + valor
                + "</b></font><br>" + etiqueta + "</center></html>";
    }

    private static String html(String texto, int ancho) {
        String seguro = texto.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;");
        return "<html><div style='width:" + ancho + "px'>" + seguro + "</div></html>";
    }

